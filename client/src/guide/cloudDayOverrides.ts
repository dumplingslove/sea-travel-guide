import type { Day} from "./data";

/**
* 云端13天行程（2026-12-06～12-18：新加坡 D1-5 / 普吉 D6-8 / 清迈 D9-10 / 曼谷 D11-13）
* 对静态内容库的逐日修正。
*
* 静态库按旧20天路线写，直接映射到13天会有三类过期：
* 1. 航段残留：D1"富国岛飞新加坡"（13天是国际直飞抵达）、D5"返程"标题＋"办理离境"
* （实际 D6 一早飞普吉，不是当天离境）；
* 2. 开门日冲突：云端 D12（周四）映射到静态 D2《周末市集》，但恰图恰仅周六日开放；
* 3. 文案过期：云端 D11（从清迈短途飞来）映射到静态 D1 的"跨洲飞行后的缓冲"。
*
* 只在云端规划生效时应用（Home.tsx），静态20天回退不受影响。
* 键为云端日号（1-13）。
*/
export function applyCloudDayOverride(
dayNum: number,
base: Day | undefined,
): Day | undefined {
if (!base) return base;
switch (dayNum) {
case 1: {
// D1 12-12 周六 新加坡：国际直飞抵达（旧文案是富国岛飞新加坡，且误链动物园详情）
return {
...base,
title: "抵达新加坡 · 滨海湾",
stops: base.stops.map((s) =>
s.name === "富国岛飞新加坡"
? {
...s,
name: "抵达樟宜机场",
detail:
"国际航班一早抵达樟宜（以实际出票时刻为准）；一家五口行李多，提前约好接机或打大车，直奔酒店寄存行李。",
}
: s,
),
};
}
case 5: {
// D5 12-16 周三 新加坡：转场前日（D6 一早飞普吉），不是"返程"当天离境
const stops = base.stops.map((s) => {
if (s.name === "回酒店收行李")
return {
...s,
detail:
"回酒店整理行李（明晨退房赶早班机飞普吉）；小印度/乌节路采购段整体砍掉——转场前日不赶场。",
};
if (s.name === "Jewel 星耀樟宜")
return {
...s,
detail:
"40米雨漩涡与室内花园（7/10 篇）：全室内、推车友好；明晨赶早班机，今天先逛透，机场人多，留足时间。",
};
if (s.name === "办理离境")
return {
...s,
name: "回酒店早休息",
detail:
"明晨早班机飞普吉：提前在线值机、复核航站楼与起飞时间，今晚早睡。",
};
return s;
});
return {
...base,
title: "多元街区 · 星耀樟宜 · 转场",
stops,
food: "Ya Kun 早餐（路线共识：亚坤早餐是新加坡高频早餐选择）；明晨赶早班机，今晚在酒店附近吃好睡好。",
tip: "转场前日只保留牛车水一圈＋Jewel，砍掉小印度/乌节路赶场。明晨飞普吉，今晚早休息。物价贵，餐厅另加约 19% 税费服务费。",
};
}
case 8: {
// D8 12-13 周日 普吉：研究建议攀牙湾与皮皮岛二选一，连排两天如实注强度
return {
...base,
tip:
base.tip +
"研究建议攀牙湾与皮皮岛二选一即可：连排两天跳岛强度大（今日 06:30 出海），体力不够可把今天换成普吉老镇深度＋海滩休息。",
};
}
case 11: {
// D11 12-16 周三 曼谷（清迈段 ordinal 1，映射静态 D1）：从清迈短途飞来，不是跨洲飞行
return {
...base,
stops: base.stops.map((s) =>
s.name === "入住酒店"
? {...s, detail: s.detail.replace("跨洲飞行", "短途飞行")}
: s,
),
};
}
case 12: {
// D12 12-17 周四 曼谷（映射静态 D2《周末市集》）：恰图恰仅周六日开放，周四换成四面佛＋暹罗商圈
const stops = base.stops.map((s) =>
s.name === "恰图恰周末市集"
? {
time: "09:30",
name: "四面佛＋暹罗商圈",
detail:
"四面佛祈福（5 篇路线帖覆盖），顺路逛暹罗商圈；恰图恰仅周六日开放——今天周四不去，本次行程与它错过。",
}
: s,
);
return {
...base,
title: "四面佛 · 黎明寺 · 唐人街",
stops,
tip: "四面佛一早去人少；餐厅订位与扫街二选一，别硬塞；打车用 Grab / Bolt 防宰。",
};
}
default:
return base;
}
}
